/**
 * Reads ui-service India cities JSON (state + city names) and emits Flyway SQL seed
 * services/los-core-service/src/main/resources/db/migration/V37__seed_geo_master_india.sql
 *
 * Run from repo root: node tools/geo/generate-india-geo-flyway-seed.mjs
 */
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(__dirname, '../..')
const srcJson = path.join(repoRoot, 'tools/geo/india-cities-flat.json')
const outSql = path.join(
  repoRoot,
  'services/los-core-service/src/main/resources/db/migration/V37__seed_geo_master_india.sql',
)

const raw = fs.readFileSync(srcJson, 'utf8')
const rows = JSON.parse(raw)

/** @type {Map<string, Set<string>>} */
const byState = new Map()
for (const r of rows) {
  const st = String(r.state ?? '').trim()
  const nm = String(r.name ?? '').trim()
  if (!st || !nm) continue
  if (!byState.has(st)) byState.set(st, new Set())
  byState.get(st).add(nm)
}

const stateNames = [...byState.keys()].sort((a, b) => a.localeCompare(b))

function esc(s) {
  return s.replace(/'/g, "''")
}

function slugCode(name, used) {
  const base = name
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-zA-Z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toUpperCase()
    .slice(0, 18)
  let c = base || 'STATE'
  let n = 0
  while (used.has(c)) {
    n += 1
    const suf = `_${n}`
    c = (base || 'STATE').slice(0, Math.max(1, 18 - suf.length)) + suf
  }
  used.add(c)
  return c
}

/** Deterministic UUID from string (stable across re-runs) */
function uuidFrom(s) {
  const h = createHash('sha256').update(s).digest()
  h[6] = (h[6] & 0x0f) | 0x40
  h[8] = (h[8] & 0x3f) | 0x80
  const hex = h.subarray(0, 16).toString('hex')
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20, 32)}`
}

const usedCodes = new Set()
const lines = []
lines.push('-- Generated by tools/geo/generate-india-geo-flyway-seed.mjs — do not edit by hand.')
lines.push('TRUNCATE TABLE state_master CASCADE;')
lines.push('')

const stateIdByName = new Map()
for (const st of stateNames) {
  const sid = uuidFrom(`state:${st}`)
  stateIdByName.set(st, sid)
  const code = slugCode(st, usedCodes)
  lines.push(
    `INSERT INTO state_master (id, state_code, state_name, is_active) VALUES ('${sid}', '${esc(code)}', '${esc(st)}', TRUE);`,
  )
}
lines.push('')

for (const st of stateNames) {
  const sid = stateIdByName.get(st)
  const cities = [...byState.get(st)].sort((a, b) => a.localeCompare(b))
  for (const c of cities) {
    const cid = uuidFrom(`city:${sid}:${c}`)
    lines.push(
      `INSERT INTO city_master (id, state_id, city_name, city_code, is_active) VALUES ('${cid}', '${sid}', '${esc(c)}', NULL, TRUE);`,
    )
  }
}

fs.writeFileSync(outSql, lines.join('\n') + '\n', 'utf8')
console.log('Wrote', outSql, 'states=', stateNames.length, 'cities=', rows.length)
